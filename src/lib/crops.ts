export const CROP_MAP: Record<string, Crop> = Object.fromEntries(
  CROPS.map((c) => [c.id, c]),
)

export function cropById(id: string): Crop | undefined {
  return CROP_MAP[id]
}

/** Crops relevant to a rainfall regime (for the rotation builder UI) */
export function cropsForRegime(regime: 'summer-rain' | 'winter-rain' | 'any'): Crop[] {
  return CROPS.filter(
    (c) => c.id !== 'fallow' && (c.regime === 'any' || c.regime === regime),
  )
}

/** Numeric mid-point water use (mm) */
export function cropWaterMid(c: Crop): number {
  return (c.waterMm[0] + c.waterMm[1]) / 2
}
